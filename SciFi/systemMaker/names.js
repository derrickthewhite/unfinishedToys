names.startNameBatch = function () {
	// make name generation independent of star generation
	names.generator = new MersenneTwister(parseInt(Math.random().toString(36).slice(2),36))
	var method = root.generation.nameMethod();
	if(method == "Mythological") names.currentNames(names.shuffleArray(names.mythology));
	if(method == "Monstrous") names.currentNames(names.shuffleArray(names.creatures));
	if(method == "Historic") names.currentNames(names.shuffleArray(names.famous));
	if(method == "Constellation-Grid") {
		names.currentNames(names.generateAlphaNumberic(1000).map(g => names.constellations[Math.round(names.generator.random() * names.constellations.length)] + "-" + g));
	}
	if(method == "grid") names.currentNames[0];
	names.gridNames(names.generateAlphaNumberic(1000));
}
names.getName = function () {
	if( root.generation.nameMethod() != names.currentNameMethod) names.startNameBatch();
	if(names.currentNames().length) return names.currentNames.pop();
	return names.getGridName();
}
names.getGridName = function () {
	if(!names.gridNames.gridNames().length)
		names.gridNames(names.generateAlphaNumberic(1000));
	return names.gridNames.pop();
}


