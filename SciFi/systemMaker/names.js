names.shuffleArray = function(jsonArray) {
  const array = [...jsonArray]; // Create a copy of the original JSON array
  for (let i = array.length - 1; i > 0; i--) {
    const j = Math.floor(names.generator.random() * (i + 1)); // Generate a random index
    // Swap array[i] and array[j]
    [array[i], array[j]] = [array[j], array[i]];
  }
  return array;
}
