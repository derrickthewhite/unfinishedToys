names.generateAlphaNumberic = function(numCombinations) {
  const combinations = new Set();
  const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';

  while (combinations.size < numCombinations) {
    let combination = '';
    if (names.generator.random() < 0.7) {
      // Generate combinations with one letter
      const letter = letters[Math.floor(names.generator.random() * letters.length)];
      const number = Math.floor(Math.pow(names.generator.random(), 2) * 999) + 1; // Adjusted distribution
      combination = `${letter}${number.toString().padStart(3, '0')}`;
    } else {
      // Generate combinations with two letters
      const letter1 = letters[Math.floor(names.generator.random() * letters.length)];
      const letter2 = letters[Math.floor(names.generator.random() * letters.length)];
      const number = Math.floor(names.generator.random() * 999) + 1;
      combination = `${letter1}${letter2}${number.toString().padStart(2, '0')}`;
    }

    combinations.add(combination);
  }

  return Array.from(combinations);
}
